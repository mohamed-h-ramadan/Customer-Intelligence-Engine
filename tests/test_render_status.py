"""Tests for scripts/render_status.py deterministic status generator."""

import subprocess
import sys

from cie.config import get_project_root


def test_render_status_generator_runs(tmp_path):
    """Verify scripts/render_status.py runs and renders all required sections."""
    root = get_project_root()
    script_path = root / "scripts" / "render_status.py"
    out_file = tmp_path / "STATUS.md"

    proc = subprocess.run(
        [sys.executable, str(script_path), "--output", str(out_file)],
        cwd=str(root),
        capture_output=True,
        text=True,
        check=False,
    )
    assert proc.returncode == 0, f"render_status.py failed:\n{proc.stderr}"
    assert out_file.is_file(), "Generated STATUS.md file missing"

    content = out_file.read_text(encoding="utf-8")
    assert "AUTO-GENERATED by scripts/render_status.py" in content
    assert "## 1. Current Verification Snapshot" in content
    assert "## 2. Platform & Contract Verification Matrix" in content
    assert "## 3. Recorded GitHub Actions CI Runs" in content
    assert "## 4. Git Commit History (`git log --oneline`)" in content
    assert "`43946052472`" in content
    assert "`43950135466`" in content
    assert "UNTESTED" in content
    assert "UNVERIFIED" in content


def test_parse_ci_coverage_xml(tmp_path):
    """Verify parse_ci_coverage_xml strictly handles missing vs provided CI XML."""
    sys.path.insert(0, str(get_project_root() / "scripts"))
    from render_status import parse_ci_coverage_xml

    # Missing file -> UNVERIFIED
    assert parse_ci_coverage_xml(None).startswith("UNVERIFIED")
    assert parse_ci_coverage_xml(tmp_path / "nonexistent.xml").startswith("UNVERIFIED")

    # Valid CI coverage.xml -> exact percentage
    xml_file = tmp_path / "coverage.xml"
    xml_file.write_text(
        '<?xml version="1.0" ?><coverage line-rate="0.8412"></coverage>', encoding="utf-8"
    )
    parsed = parse_ci_coverage_xml(xml_file)
    assert "84.12%" in parsed
    assert "coverage.xml" in parsed
