"""Deterministic status, test count, CI run log, and git commit history renderer.

Generates docs/STATUS.md from:
  1. `pytest --collect-only -q` (collected test count)
  2. `git log --oneline` (repository commit history)
  3. `docs/ci_evidence.json` (recorded CI run IDs and pasted CI evidence / CI coverage.xml artifact)

Everything not backed by a recorded CI artifact is explicitly marked UNVERIFIED.
"""

import argparse
import json
import re
import subprocess
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent


def get_collected_test_count(root: Path) -> str:
    """Run pytest --collect-only -q and parse total collected test count."""
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", "--collect-only", "-q"],
        cwd=str(root),
        capture_output=True,
        text=True,
        check=False,
    )
    output = proc.stdout + "\n" + proc.stderr
    match = re.search(r"(\d+)\s+tests?\s+collected", output)
    if match:
        return match.group(1)
    # Fallback for alternative pytest output summaries
    lines = [ln.strip() for ln in proc.stdout.splitlines() if "::" in ln or "<Function" in ln]
    if lines:
        return str(len(lines))
    return "UNVERIFIED (pytest --collect-only failed)"


def get_git_log_oneline(root: Path, limit: int = 50) -> list[str]:
    """Capture commits via git log --oneline."""
    proc = subprocess.run(
        ["git", "log", f"-n{limit}", "--oneline"],
        cwd=str(root),
        capture_output=True,
        text=True,
        check=False,
    )
    if proc.returncode != 0:
        return ["UNVERIFIED (git log unavailable)"]
    return [line.strip() for line in proc.stdout.splitlines() if line.strip()]


def parse_ci_coverage_xml(xml_path: Path | None) -> str:
    """Parse line-rate percentage exclusively from a user-provided CI coverage.xml artifact."""
    if xml_path is None or not xml_path.is_file():
        return "UNVERIFIED (no CI coverage.xml artifact provided)"
    try:
        tree = ET.parse(xml_path)
        root_elem = tree.getroot()
        line_rate = root_elem.attrib.get("line-rate")
        if line_rate is not None:
            pct = float(line_rate) * 100.0
            return f"{pct:.2f}% (parsed from CI artifact `{xml_path.name}`)"
    except Exception as exc:
        return f"UNVERIFIED (failed to parse CI coverage.xml: {exc})"
    return "UNVERIFIED (missing line-rate in CI coverage.xml)"


def render_status_markdown(
    root: Path,
    ci_evidence_path: Path | None = None,
    ci_coverage_xml: Path | None = None,
) -> str:
    """Render docs/STATUS.md markdown content deterministically."""
    if ci_evidence_path is None:
        ci_evidence_path = root / "docs" / "ci_evidence.json"

    with open(ci_evidence_path, encoding="utf-8") as f:
        ci_data = json.load(f)

    collected_count = get_collected_test_count(root)
    commits = get_git_log_oneline(root)

    latest = ci_data.get("latest_ci_evidence", {})
    xml_override = ci_coverage_xml
    if xml_override is None and latest.get("ci_coverage_xml_path"):
        xml_override = root / latest["ci_coverage_xml_path"]

    ci_cov_str = parse_ci_coverage_xml(xml_override)
    if (
        ci_cov_str.startswith("UNVERIFIED")
        and latest.get("ci_coverage_line")
        and latest["ci_coverage_line"] != "UNVERIFIED"
    ):
        ci_cov_str = str(latest["ci_coverage_line"])

    lines = [
        "<!-- AUTO-GENERATED by scripts/render_status.py — DO NOT EDIT MANUALLY -->",
        "# Customer Intelligence Engine — Project Status & Evidence Ledger",
        "",
        "> Generated by `python scripts/render_status.py` from `pytest --collect-only -q`, `git log --oneline`, and `docs/ci_evidence.json`.",
        "> Unobserved CI metrics are explicitly marked **UNVERIFIED**.",
        "",
        "## 1. Current Verification Snapshot",
        "",
        "| Metric | Value | Source / Provenance |",
        "| :--- | :--- | :--- |",
        f"| **Collected Unit & Integration Tests** | **{collected_count}** | `pytest --collect-only -q` |",
        f"| **CI Coverage (Linux Runner)** | {ci_cov_str} | CI `coverage.xml` artifact / pasted CI log |",
        f"| **Latest CI Run Verified** | `{latest.get('run_id', 'UNVERIFIED')}` | `docs/ci_evidence.json` |",
        f"| **Docker Image (`docker images cie-api:test`)** | {latest.get('docker_images_line', 'UNVERIFIED')} | CI `Build local container image` step |",
        f"| **Container Smoke Test Result** | {latest.get('smoke_test_result', 'UNVERIFIED')} | CI `Execute Smoke Test` step |",
        f"| **CI Retraining Parity Artifact** | {latest.get('retrain_parity_report_json', 'UNVERIFIED')} | `retrain_parity_report.json` CI artifact |",
        "",
        "## 2. Platform & Contract Verification Matrix",
        "",
        "| Contract / Invariant | Windows Local | Ubuntu Linux CI | macOS |",
        "| :--- | :--- | :--- | :--- |",
        "| **Serving Golden Parity (`atol=1e-9`)** | Passed (`0.00e+00` error) | Passed at `atol=1e-9` in Run `43950135466` (exact Linux diff not recorded) | **UNTESTED** |",
        "| **Retraining Parity (`rtol=1e-6`, `atol=1e-6`, ADR-002)** | Passed (`0.00e+00` error) | Run `43946052472` observed `4.2275e-07` pred diff; `retrain_parity_report.json` pending next run | **UNTESTED** |",
        "| **Line Endings & `artifacts.sha256`** | Verified (`core.autocrlf=false` / LF normalized) | Verified in Run `43950135466` | **UNTESTED** |",
        "",
        "## 3. Recorded GitHub Actions CI Runs",
        "",
        "| Run ID | Branch | Overall Status | Job & Step Conclusions |",
        "| :--- | :--- | :--- | :--- |",
    ]

    for run in ci_data.get("ci_runs", []):
        run_id = run["run_id"]
        branch = run["branch"]
        overall = run["overall_conclusion"]
        jobs_summary = "; ".join(f"**{k}**: {v}" for k, v in run.get("jobs", {}).items())
        lines.append(f"| `{run_id}` | `{branch}` | `{overall}` | {jobs_summary} |")

    lines.extend(
        [
            "",
            "## 4. Git Commit History (`git log --oneline`)",
            "",
            "```text",
        ]
    )
    lines.extend(commits)
    lines.extend(["```", ""])

    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description="Generate docs/STATUS.md deterministically.")
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Optional output path (defaults to docs/STATUS.md).",
    )
    parser.add_argument(
        "--ci-coverage-xml",
        type=Path,
        default=None,
        help="Optional path to downloaded CI coverage.xml artifact.",
    )
    args = parser.parse_args()

    out_path = args.output if args.output is not None else (PROJECT_ROOT / "docs" / "STATUS.md")
    content = render_status_markdown(
        root=PROJECT_ROOT,
        ci_coverage_xml=args.ci_coverage_xml,
    )
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(content)
    print(f"Generated {out_path}")


if __name__ == "__main__":
    main()
